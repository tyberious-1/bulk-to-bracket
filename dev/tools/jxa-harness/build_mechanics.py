#!/usr/bin/env python3
"""Collect one rules-reminder text per Scryfall keyword ability (not keyword actions: those are verbs inside spell text) and write js/analysis/mechanics-data.js.

Usage (from the repo root): python3 -I dev/tools/jxa-harness/build_mechanics.py [--since 2025-01-01]

The reminder text on a keyword card ("Warp {1}{R} (You may cast this card from your hand for its warp cost...)") is
Scryfall's own explanation of the mechanic. abilities.js runs its effect labels over it, so a keyword line gets read
without a hand-written rule. Re-run after each new set: it reads owned_raw.json first (free), then asks Scryfall for
any keyword it still has no reminder for (one search each, public, read-only), newest cards first.
"""
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / "js" / "analysis" / "mechanics-data.js"
HDR = {"User-Agent": "bulk-to-bracket-measure/1.0", "Accept": "application/json"}


def get(url):
    return json.loads(urllib.request.urlopen(urllib.request.Request(url, headers=HDR), timeout=30).read())


def catalog(name):
    return get("https://api.scryfall.com/catalog/" + name)["data"]


def card_text(c):
    return c.get("oracle_text") or "\n".join(f.get("oracle_text", "") for f in c.get("card_faces") or [])


def find_reminder(keyword, text):
    kw = re.escape(keyword)
    # keyword at the start of a line (or after an ability word), then its cost or number, then the reminder
    m = re.search(r"(?:^|\n)(?:[^\n—]{0,30} — )?" + kw + r"\b[^()\n]{0,40}\(([^()\n]{12,400})\)", text, re.I)
    if not m:
        m = re.search(r"\b" + kw + r"\b[^()\n]{0,30}\(([^()\n]{12,400})\)", text, re.I)
    return m.group(1).strip() if m else None


def main():
    keywords = sorted({k.lower() for n in ("keyword-abilities",) for k in catalog(n)})
    found = {}
    owned = json.loads((REPO / "dev/tools/jxa-harness/owned_raw.json").read_text())
    for c in owned:
        t = card_text(c)
        for k in keywords:
            if k not in found and k in t.lower():
                r = find_reminder(k, t)
                if r:
                    found[k] = r
    missing = [k for k in keywords if k not in found]
    print(len(found), "from owned cards;", len(missing), "to ask Scryfall", file=sys.stderr)
    for k in missing:
        q = urllib.parse.urlencode({"q": 'o:"%s" game:paper' % k, "order": "released", "dir": "desc", "unique": "cards"})
        try:
            for c in get("https://api.scryfall.com/cards/search?" + q)["data"]:
                r = find_reminder(k, card_text(c))
                if r:
                    found[k] = r
                    break
        except Exception:
            pass
        time.sleep(0.12)
    body = ",\n".join("  %s: %s" % (json.dumps(k), json.dumps(found[k])) for k in sorted(found))
    OUT.write_text(
        "// Generated by dev/tools/jxa-harness/build_mechanics.py -- do not edit by hand. One rules-reminder text per keyword\n"
        "// (Scryfall's keyword catalogs, reminder taken from a card that uses it), read by abilities.js so a keyword line\n"
        "// is labeled by what its own reminder says. %d of %d keywords have a reminder.\n"
        "const MECHANIC_REMINDERS = {\n%s\n};\n" % (len(found), len(keywords), body)
    )
    print("wrote", OUT, len(found), "of", len(keywords), "keywords", file=sys.stderr)


main()
