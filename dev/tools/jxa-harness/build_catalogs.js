// Writes js/analysis/catalog-data.js from Scryfall's official catalogs (creature types, keyword abilities,
// ability words). Run from the repo root after a set release: node dev/tools/jxa-harness/build_catalogs.js
const fs = require("fs");
const get = async (name) => {
  const res = await fetch("https://api.scryfall.com/catalog/" + name, { headers: { "User-Agent": "bulk-to-bracket-catalogs/1.0", Accept: "application/json" } });
  if (!res.ok) throw new Error(name + " " + res.status);
  return (await res.json()).data.map((x) => x.toLowerCase()).sort();
};
(async () => {
  const types = await get("creature-types");
  const keywords = await get("keyword-abilities");
  const words = await get("ability-words");
  const body = `// Generated by dev/tools/jxa-harness/build_catalogs.js -- do not edit by hand. Scryfall's catalogs, lowercased: every creature
// type, keyword ability and ability word. themes.js resolveCatalogTheme reads them so a theme named "flying" or "eldrazi"
// matches cards by their keywords and subtypes instead of by the word in their text. ${types.length} types, ${keywords.length} keywords, ${words.length} ability words.
const CATALOG_CREATURE_TYPES = new Set(${JSON.stringify(types)});
const CATALOG_KEYWORDS = new Set(${JSON.stringify(keywords.concat(words))});
`;
  fs.writeFileSync("js/analysis/catalog-data.js", body);
  console.log("wrote js/analysis/catalog-data.js", types.length, keywords.length, words.length);
})();
